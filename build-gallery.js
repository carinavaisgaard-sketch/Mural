// Scans assets/images/<location>/ folders and writes gallery-data.js.
// server.js calls this on every page load. Run directly to write a static file:  node build-gallery.js
//
// Optional: put an info.json in a location folder to override the defaults:
//   { "title": "Hobbyhuset", "place": "Aarhus, DK", "year": "2025", "description": "..." }

const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const IMAGES_DIR = path.join(ROOT, "assets", "images");
const OUTPUT = path.join(ROOT, "gallery-data.js");
const IMAGE_EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif"]);

function prettify(name) {
  return name
    .replace(/[-_]+/g, " ")
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

function readInfo(dir) {
  const file = path.join(dir, "info.json");
  if (!fs.existsSync(file)) return {};
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (err) {
    console.warn(`Skipping invalid ${path.relative(ROOT, file)}: ${err.message}`);
    return {};
  }
}

function scanLocations() {
  if (!fs.existsSync(IMAGES_DIR)) return [];
  return fs
    .readdirSync(IMAGES_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => {
      const dir = path.join(IMAGES_DIR, d.name);
      const images = fs
        .readdirSync(dir)
        .filter((f) => IMAGE_EXT.has(path.extname(f).toLowerCase()))
        .sort()
        .map((f) => path.posix.join("assets", "images", d.name, f));
      const info = readInfo(dir);
      return {
        id: d.name.toLowerCase().replace(/[^a-z0-9]+/g, "-"),
        title: info.title || prettify(d.name),
        place: info.place || "",
        year: info.year || "",
        description: info.description || "",
        images,
      };
    })
    .filter((loc) => loc.images.length > 0)
    .sort((a, b) => a.title.localeCompare(b.title));
}

function buildGalleryScript(locations = scanLocations()) {
  const banner = "// Generated by build-gallery.js. Do not edit by hand.\n";
  return `${banner}window.GALLERY = ${JSON.stringify(locations, null, 2)};\n`;
}

module.exports = { scanLocations, buildGalleryScript };

// Run directly (node build-gallery.js) to write a static gallery-data.js, e.g. before deploying.
if (require.main === module) {
  const locations = scanLocations();
  fs.writeFileSync(OUTPUT, buildGalleryScript(locations));
  const total = locations.reduce((n, l) => n + l.images.length, 0);
  console.log(`Wrote ${path.relative(ROOT, OUTPUT)}: ${locations.length} locations, ${total} images.`);
}
